-- VAX WIJAYA — SVP floating attendance v1
-- Isolated from locked employee attendance/geofence engine.

create table if not exists public.svp_absensi_v1 (
    id bigint generated by default as identity primary key,
    profile_id uuid not null references public.profiles(id),
    karyawan_id bigint not null references public.karyawan(id),
    tanggal date not null,
    jam_masuk time without time zone,
    jam_pulang time without time zone,
    latitude_masuk double precision,
    longitude_masuk double precision,
    accuracy_masuk double precision,
    alamat_masuk text,
    latitude_pulang double precision,
    longitude_pulang double precision,
    accuracy_pulang double precision,
    alamat_pulang text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint svp_absensi_v1_karyawan_tanggal_key unique (karyawan_id,tanggal)
);

alter table public.svp_absensi_v1 enable row level security;

comment on table public.svp_absensi_v1 is
'Absensi khusus SPV/SVP floating. Tidak memakai geofence cabang, jam kerja global, atau denda keterlambatan. GPS tetap wajib dan lokasi aktual disimpan.';

create index if not exists svp_absensi_v1_tanggal_idx
on public.svp_absensi_v1(tanggal desc);

create index if not exists svp_absensi_v1_profile_idx
on public.svp_absensi_v1(profile_id,tanggal desc);

create or replace function public.svp_absensi_self_today_v1()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
    v_uid uuid := auth.uid();
    v_profile public.profiles%rowtype;
    v_k public.karyawan%rowtype;
    v_row public.svp_absensi_v1%rowtype;
    v_day date := (now() at time zone 'Asia/Jakarta')::date;
begin
    if v_uid is null then raise exception 'SESSION_INVALID'; end if;

    select * into v_profile
    from public.profiles
    where id = v_uid
      and aktif is true
      and lower(trim(role)) in ('svp','spv')
    limit 1;

    if not found then raise exception 'SVP_ACCESS_REQUIRED'; end if;
    if v_profile.karyawan_id is null then raise exception 'SVP_KARYAWAN_MAPPING_MISSING'; end if;

    select * into v_k from public.karyawan where id = v_profile.karyawan_id limit 1;
    if not found then raise exception 'SVP_KARYAWAN_NOT_FOUND'; end if;

    select * into v_row
    from public.svp_absensi_v1
    where karyawan_id = v_profile.karyawan_id
      and tanggal = v_day
    limit 1;

    return jsonb_build_object(
        'ok', true,
        'tanggal', v_day,
        'profile_id', v_profile.id,
        'karyawan_id', v_profile.karyawan_id,
        'nama', coalesce(v_k.nama_karyawan, v_profile.nama),
        'jam_masuk', v_row.jam_masuk,
        'jam_pulang', v_row.jam_pulang,
        'alamat_masuk', v_row.alamat_masuk,
        'alamat_pulang', v_row.alamat_pulang
    );
end;
$function$;

create or replace function public.svp_absen_self_v1(
    p_action text,
    p_lat double precision,
    p_lon double precision,
    p_accuracy double precision,
    p_address text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
    v_uid uuid := auth.uid();
    v_profile public.profiles%rowtype;
    v_k public.karyawan%rowtype;
    v_row public.svp_absensi_v1%rowtype;
    v_day date := (now() at time zone 'Asia/Jakarta')::date;
    v_clock time := (now() at time zone 'Asia/Jakarta')::time(0);
    v_action text := upper(trim(coalesce(p_action,'')));
    v_address text := nullif(trim(coalesce(p_address,'')),'');
begin
    if v_uid is null then raise exception 'SESSION_INVALID'; end if;

    select * into v_profile
    from public.profiles
    where id = v_uid
      and aktif is true
      and lower(trim(role)) in ('svp','spv')
    limit 1;

    if not found then raise exception 'SVP_ACCESS_REQUIRED'; end if;
    if v_profile.karyawan_id is null then raise exception 'SVP_KARYAWAN_MAPPING_MISSING'; end if;

    select * into v_k from public.karyawan where id = v_profile.karyawan_id limit 1;
    if not found then raise exception 'SVP_KARYAWAN_NOT_FOUND'; end if;

    if v_action not in ('MASUK','PULANG') then raise exception 'ACTION_INVALID'; end if;

    if p_lat is null or p_lon is null or p_accuracy is null
       or p_lat::text in ('NaN','Infinity','-Infinity')
       or p_lon::text in ('NaN','Infinity','-Infinity')
       or p_accuracy::text in ('NaN','Infinity','-Infinity')
       or p_lat not between -90 and 90
       or p_lon not between -180 and 180
       or p_accuracy <= 0
       or p_accuracy > 100 then
        raise exception 'GPS_INVALID';
    end if;

    if v_action = 'MASUK' then
        insert into public.svp_absensi_v1 (
            profile_id,karyawan_id,tanggal,jam_masuk,
            latitude_masuk,longitude_masuk,accuracy_masuk,alamat_masuk
        ) values (
            v_profile.id,v_profile.karyawan_id,v_day,v_clock,
            p_lat,p_lon,p_accuracy,v_address
        )
        on conflict (karyawan_id,tanggal) do nothing
        returning * into v_row;

        if v_row.id is null then raise exception 'ABSEN_MASUK_SUDAH_TERCATAT'; end if;
    else
        update public.svp_absensi_v1
           set jam_pulang = v_clock,
               latitude_pulang = p_lat,
               longitude_pulang = p_lon,
               accuracy_pulang = p_accuracy,
               alamat_pulang = v_address,
               updated_at = now()
         where karyawan_id = v_profile.karyawan_id
           and tanggal = v_day
           and jam_masuk is not null
           and jam_pulang is null
        returning * into v_row;

        if v_row.id is null then raise exception 'ABSEN_PULANG_TIDAK_TERSEDIA'; end if;
    end if;

    return jsonb_build_object(
        'ok', true,
        'action', v_action,
        'id', v_row.id,
        'tanggal', v_row.tanggal,
        'karyawan_id', v_row.karyawan_id,
        'nama', coalesce(v_k.nama_karyawan, v_profile.nama),
        'jam_masuk', v_row.jam_masuk,
        'jam_pulang', v_row.jam_pulang,
        'alamat_masuk', v_row.alamat_masuk,
        'alamat_pulang', v_row.alamat_pulang
    );
end;
$function$;

create or replace function public.svp_absensi_owner_list_v1(
    p_from date,
    p_to date
)
returns table (
    id bigint,
    tanggal date,
    karyawan_id bigint,
    nama_karyawan text,
    jam_masuk time without time zone,
    jam_pulang time without time zone,
    latitude_masuk double precision,
    longitude_masuk double precision,
    accuracy_masuk double precision,
    alamat_masuk text,
    latitude_pulang double precision,
    longitude_pulang double precision,
    accuracy_pulang double precision,
    alamat_pulang text
)
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
    v_uid uuid := auth.uid();
begin
    if v_uid is null or not exists (
        select 1 from public.profiles
        where profiles.id = v_uid
          and profiles.aktif is true
          and lower(trim(profiles.role)) = 'owner'
    ) then
        raise exception 'OWNER_ACCESS_REQUIRED';
    end if;

    return query
    select
        a.id,a.tanggal,a.karyawan_id,k.nama_karyawan,
        a.jam_masuk,a.jam_pulang,
        a.latitude_masuk,a.longitude_masuk,a.accuracy_masuk,a.alamat_masuk,
        a.latitude_pulang,a.longitude_pulang,a.accuracy_pulang,a.alamat_pulang
    from public.svp_absensi_v1 a
    join public.karyawan k on k.id = a.karyawan_id
    where a.tanggal between p_from and p_to
    order by a.tanggal desc, a.id desc;
end;
$function$;

revoke all on public.svp_absensi_v1 from anon, authenticated;
grant execute on function public.svp_absensi_self_today_v1() to authenticated;
grant execute on function public.svp_absen_self_v1(text,double precision,double precision,double precision,text) to authenticated;
grant execute on function public.svp_absensi_owner_list_v1(date,date) to authenticated;
