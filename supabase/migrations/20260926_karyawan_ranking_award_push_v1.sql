-- ERP VAX: production Web Push + one-time celebration state for Ranking 1 Semua Cabang.
-- Applied to Supabase production on 2026-09-26.

create table if not exists public.karyawan_push_subscription_v1 (
  id bigint generated by default as identity primary key,
  karyawan_id bigint not null references public.karyawan(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  user_agent text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  disabled_at timestamptz,
  constraint karyawan_push_subscription_v1_endpoint_len check (char_length(endpoint) between 16 and 4096),
  constraint karyawan_push_subscription_v1_p256dh_len check (char_length(p256dh) between 16 and 1024),
  constraint karyawan_push_subscription_v1_auth_len check (char_length(auth) between 8 and 1024)
);

create index if not exists karyawan_push_subscription_v1_employee_active_idx
  on public.karyawan_push_subscription_v1(karyawan_id,active)
  where active is true and disabled_at is null;

alter table public.karyawan_push_subscription_v1 enable row level security;
revoke all on table public.karyawan_push_subscription_v1 from anon,authenticated;
grant select,insert,update,delete on table public.karyawan_push_subscription_v1 to service_role;

create table if not exists public.karyawan_ranking_award_v1 (
  id bigint generated by default as identity primary key,
  karyawan_id bigint not null references public.karyawan(id) on delete cascade,
  activity_date date not null,
  scope text not null default 'GLOBAL' check(scope='GLOBAL'),
  rank integer not null default 1 check(rank=1),
  total_service numeric not null default 0,
  total_income numeric not null default 0,
  cabang_id bigint references public.cabang(id),
  title text not null default 'SELAMAT, ANDA RANGKING 1 DI SEMUA CABANG',
  body text not null default 'Selamat, Anda berhasil meraih Ranking 1 di Semua Cabang. Semoga hasil kerja hari ini membawa rezeki yang baik dan menambah semangat Anda. Gunakan sebagian hasil tersebut untuk menunjang penampilan kerja atau kebutuhan alat kerja agar performa tetap optimal.',
  push_attempts integer not null default 0,
  last_push_error text,
  notified_at timestamptz,
  opened_at timestamptz,
  celebrated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(karyawan_id,activity_date,scope)
);

create index if not exists karyawan_ranking_award_v1_pending_idx
  on public.karyawan_ranking_award_v1(karyawan_id,activity_date desc)
  where celebrated_at is null;

alter table public.karyawan_ranking_award_v1 enable row level security;
revoke all on table public.karyawan_ranking_award_v1 from anon,authenticated;
grant select,insert,update,delete on table public.karyawan_ranking_award_v1 to service_role;

create or replace function public.karyawan_push_subscription_upsert_self_v1(
  p_token text,p_endpoint text,p_p256dh text,p_auth text,p_user_agent text default null
) returns jsonb
language plpgsql security definer set search_path to 'public','pg_temp'
as $$
declare v_employee_id bigint; v_id bigint;
begin
  v_employee_id:=public.karyawan_session_id_from_token(p_token);
  if v_employee_id is null then return jsonb_build_object('ok',false,'reason','SESSION_INVALID'); end if;
  if coalesce(char_length(trim(p_endpoint)),0)<16 or char_length(p_endpoint)>4096
     or coalesce(char_length(trim(p_p256dh)),0)<16 or char_length(p_p256dh)>1024
     or coalesce(char_length(trim(p_auth)),0)<8 or char_length(p_auth)>1024
  then return jsonb_build_object('ok',false,'reason','SUBSCRIPTION_INVALID'); end if;

  insert into public.karyawan_push_subscription_v1(
    karyawan_id,endpoint,p256dh,auth,user_agent,active,updated_at,last_seen_at,disabled_at
  ) values(
    v_employee_id,trim(p_endpoint),trim(p_p256dh),trim(p_auth),
    left(nullif(trim(coalesce(p_user_agent,'')),''),500),true,now(),now(),null
  )
  on conflict(endpoint) do update set
    karyawan_id=excluded.karyawan_id,p256dh=excluded.p256dh,auth=excluded.auth,
    user_agent=excluded.user_agent,active=true,updated_at=now(),last_seen_at=now(),disabled_at=null
  returning id into v_id;
  return jsonb_build_object('ok',true,'subscription_id',v_id);
end $$;

create or replace function public.karyawan_push_subscription_disable_self_v1(
  p_token text,p_endpoint text
) returns jsonb
language plpgsql security definer set search_path to 'public','pg_temp'
as $$
declare v_employee_id bigint;
begin
  v_employee_id:=public.karyawan_session_id_from_token(p_token);
  if v_employee_id is null then return jsonb_build_object('ok',false,'reason','SESSION_INVALID'); end if;
  update public.karyawan_push_subscription_v1
     set active=false,disabled_at=now(),updated_at=now()
   where karyawan_id=v_employee_id and endpoint=p_endpoint;
  return jsonb_build_object('ok',true);
end $$;

create or replace function public.karyawan_ranking_award_candidates_v1(p_date date)
returns table(
  karyawan_id bigint,activity_date date,cabang_id bigint,barber_name text,cabang_name text,
  rank_company integer,total_service numeric,total_income numeric
)
language sql stable security definer set search_path to 'public','pg_temp'
as $$
  with normalized as (
    select
      case when s.employee_id is not null then 'e:'||s.employee_id::text
           else 'p:'||s.cabang_id::text||':'||upper(trim(coalesce(s.provider_name_normalized,s.provider_name_raw,''))) end identity_key,
      s.employee_id,
      coalesce(nullif(trim(s.provider_name_raw),''),nullif(trim(s.provider_name_normalized),''),'—') barber_name,
      s.cabang_id,c.nama_cabang,coalesce(s.total_service,0)::numeric total_service,coalesce(s.total_income,0)::numeric total_income
    from public.provider_sales_daily_source s
    join public.cabang c on c.id=s.cabang_id and c.aktif is true
    where s.activity_date=p_date
  ), aggregated as (
    select identity_key,employee_id,max(barber_name) barber_name,cabang_id,max(nama_cabang) nama_cabang,
           sum(total_service) total_service,sum(total_income) total_income
    from normalized
    group by identity_key,employee_id,cabang_id
    having sum(total_service)>0
  ), ranked as (
    select a.*,row_number() over(order by a.total_service desc,a.total_income desc,a.barber_name asc)::integer rank_company
    from aggregated a
  )
  select r.employee_id,p_date,r.cabang_id,r.barber_name,r.nama_cabang,r.rank_company,r.total_service,r.total_income
  from ranked r
  join public.karyawan k on k.id=r.employee_id and k.aktif is true and lower(trim(coalesce(k.jabatan,'')))='capster'
  where r.rank_company=1 and r.employee_id is not null
$$;

create or replace function public.karyawan_ranking_award_claim_self_v1(
  p_token text,p_activity_date date
) returns jsonb
language plpgsql security definer set search_path to 'public','pg_temp'
as $$
declare v_employee_id bigint; v_row public.karyawan_ranking_award_v1%rowtype;
begin
  v_employee_id:=public.karyawan_session_id_from_token(p_token);
  if v_employee_id is null then return jsonb_build_object('ok',false,'reason','SESSION_INVALID'); end if;
  select * into v_row from public.karyawan_ranking_award_v1
   where karyawan_id=v_employee_id and activity_date=p_activity_date and scope='GLOBAL' limit 1;
  if not found then return jsonb_build_object('ok',false,'reason','NOT_FOUND'); end if;
  if v_row.celebrated_at is not null then
    return jsonb_build_object('ok',true,'show',false,'reason','ALREADY_CELEBRATED','award_id',v_row.id);
  end if;
  update public.karyawan_ranking_award_v1 set opened_at=coalesce(opened_at,now()),updated_at=now() where id=v_row.id;
  return jsonb_build_object('ok',true,'show',true,'award_id',v_row.id,'activity_date',v_row.activity_date,
    'rank',v_row.rank,'total_service',v_row.total_service,'title',v_row.title,'body',v_row.body);
end $$;

create or replace function public.karyawan_ranking_award_celebrated_self_v1(
  p_token text,p_award_id bigint
) returns jsonb
language plpgsql security definer set search_path to 'public','pg_temp'
as $$
declare v_employee_id bigint;
begin
  v_employee_id:=public.karyawan_session_id_from_token(p_token);
  if v_employee_id is null then return jsonb_build_object('ok',false,'reason','SESSION_INVALID'); end if;
  update public.karyawan_ranking_award_v1
     set opened_at=coalesce(opened_at,now()),celebrated_at=coalesce(celebrated_at,now()),updated_at=now()
   where id=p_award_id and karyawan_id=v_employee_id;
  if not found then return jsonb_build_object('ok',false,'reason','NOT_FOUND'); end if;
  return jsonb_build_object('ok',true);
end $$;

