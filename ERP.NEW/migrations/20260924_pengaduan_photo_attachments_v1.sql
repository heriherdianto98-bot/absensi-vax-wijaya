-- ERP VAX Pengaduan photo attachments V1
-- Private storage, max 5 photos per submission handled by Edge Function.
-- Binary files are purged after 40 days; metadata/audit history remains.

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values (
  'erp-pengaduan-photos',
  'erp-pengaduan-photos',
  false,
  5242880,
  array['image/jpeg','image/png','image/webp']::text[]
)
on conflict (id) do update
set public=false,
    file_size_limit=excluded.file_size_limit,
    allowed_mime_types=excluded.allowed_mime_types;

create table if not exists public.erp_pengaduan_photo (
  id bigint generated by default as identity primary key,
  pengaduan_id bigint not null references public.erp_pengaduan(id) on delete cascade,
  uploaded_by_kind text not null check (uploaded_by_kind in ('KARYAWAN','SVP','OWNER')),
  uploaded_by_karyawan_id bigint references public.karyawan(id),
  uploaded_by_user_id uuid references auth.users(id),
  storage_bucket text not null default 'erp-pengaduan-photos',
  storage_path text not null unique,
  original_name text not null,
  mime_type text not null check (mime_type in ('image/jpeg','image/png','image/webp')),
  size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 5242880),
  created_at timestamptz not null default now(),
  file_deleted_at timestamptz,
  delete_reason text
);

create index if not exists erp_pengaduan_photo_ticket_created_idx
  on public.erp_pengaduan_photo(pengaduan_id,created_at,id);

create index if not exists erp_pengaduan_photo_cleanup_idx
  on public.erp_pengaduan_photo(created_at)
  where file_deleted_at is null;

alter table public.erp_pengaduan_photo enable row level security;
revoke all on public.erp_pengaduan_photo from anon, authenticated;

insert into public.erp_internal_job_secrets(job_name,secret,created_at,rotated_at)
values (
  'pengaduan_photo_cleanup',
  encode(gen_random_bytes(32),'hex'),
  now(),
  now()
)
on conflict (job_name) do nothing;

create or replace function public.run_pengaduan_photo_cleanup()
returns bigint
language plpgsql
security definer
set search_path='public','extensions'
as $$
declare
  v_secret text;
  v_request_id bigint;
begin
  select secret into v_secret
  from public.erp_internal_job_secrets
  where job_name='pengaduan_photo_cleanup';

  if v_secret is null then
    raise exception 'pengaduan photo cleanup secret missing';
  end if;

  select net.http_post(
    url := 'https://cmtuufwzjshixivykbjf.supabase.co/functions/v1/pengaduan-photo-cleanup',
    headers := jsonb_build_object(
      'Content-Type','application/json',
      'x-erp-cleanup-token',v_secret
    ),
    body := jsonb_build_object('source','pg_cron')
  ) into v_request_id;

  return v_request_id;
end;
$$;

revoke all on function public.run_pengaduan_photo_cleanup() from public,anon,authenticated;

do $$
begin
  if not exists (select 1 from cron.job where jobname='pengaduan-photo-cleanup-daily') then
    perform cron.schedule(
      'pengaduan-photo-cleanup-daily',
      '40 18 * * *',
      'select public.run_pengaduan_photo_cleanup();'
    );
  end if;
end
$$;
