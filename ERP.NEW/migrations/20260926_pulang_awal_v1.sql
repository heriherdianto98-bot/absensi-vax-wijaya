-- VAX WIJAYA ERP
-- Pulang Lebih Awal v1
-- Additive module: employee request -> SPV decision -> attendance status canonicalized.
-- Owner access is read-only through pulang_awal_list_reviewer_v1().

create table if not exists public.pengajuan_pulang_awal (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  karyawan_id bigint not null references public.karyawan(id),
  cabang_id bigint references public.cabang(id),
  absensi_id bigint not null references public.absensi(id),
  tanggal date not null,
  jenis text not null check (upper(jenis) in ('IZIN','SAKIT','LIBUR')),
  alasan text not null,
  bukti_path text not null,
  status text not null default 'MENUNGGU_SPV'
    check (status in ('MENUNGGU_SPV','DISETUJUI_SPV','DITOLAK_SPV')),
  jam_masuk_snapshot time,
  jam_pulang_sebelum time,
  jam_pulang_setelah time,
  absensi_status_sebelum text,
  absensi_status_setelah text,
  status_absensi_sebelum char(1),
  status_absensi_setelah char(1),
  denda_sebelum integer not null default 0,
  status_denda_sebelum text,
  spv_user_id uuid references auth.users(id),
  spv_catatan text,
  spv_reviewed_at timestamptz
);

create index if not exists idx_pengajuan_pulang_awal_status_created
  on public.pengajuan_pulang_awal(status, created_at desc);

create index if not exists idx_pengajuan_pulang_awal_karyawan_tanggal
  on public.pengajuan_pulang_awal(karyawan_id, tanggal desc);

create unique index if not exists uq_pengajuan_pulang_awal_active_day
  on public.pengajuan_pulang_awal(karyawan_id, tanggal)
  where status in ('MENUNGGU_SPV','DISETUJUI_SPV');

create table if not exists public.pengajuan_pulang_awal_audit (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  pengajuan_id bigint not null references public.pengajuan_pulang_awal(id),
  actor_user_id uuid,
  actor_karyawan_id bigint,
  actor_role text not null,
  action text not null,
  status_before text,
  status_after text,
  detail jsonb not null default '{}'::jsonb
);

alter table public.pengajuan_pulang_awal enable row level security;
alter table public.pengajuan_pulang_awal_audit enable row level security;

revoke all on public.pengajuan_pulang_awal from anon, authenticated;
revoke all on public.pengajuan_pulang_awal_audit from anon, authenticated;

create or replace function public.submit_pulang_awal_v1(
  p_session_token text,
  p_jenis text,
  p_alasan text,
  p_bukti_path text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_kid bigint;
  v_day date := (now() at time zone 'Asia/Jakarta')::date;
  v_kind text := upper(trim(coalesce(p_jenis,'')));
  v_reason text := trim(coalesce(p_alasan,''));
  v_proof text := trim(coalesce(p_bukti_path,''));
  v_abs public.absensi%rowtype;
  v_id bigint;
begin
  v_kid := public.karyawan_session_id_from_token(p_session_token);

  if v_kid is null then
    raise exception 'SESSION_INVALID: login ulang diperlukan';
  end if;

  if v_kind not in ('IZIN','SAKIT','LIBUR') then
    raise exception 'JENIS_INVALID';
  end if;

  if char_length(v_reason) < 3 then
    raise exception 'ALASAN_WAJIB: minimal 3 karakter';
  end if;

  if v_proof = '' then
    raise exception 'BUKTI_WAJIB';
  end if;

  select a.*
    into v_abs
    from public.absensi a
   where a.karyawan_id = v_kid
     and a.tanggal = v_day
   for update;

  if not found or v_abs.jam_masuk is null then
    raise exception 'BELUM_ABSEN_MASUK: pengajuan pulang lebih awal hanya untuk karyawan yang sudah absen masuk';
  end if;

  if v_abs.jam_pulang is not null then
    raise exception 'SUDAH_ABSEN_PULANG';
  end if;

  if upper(trim(coalesce(v_abs.status,''))) in ('IZIN','SAKIT','LIBUR') then
    raise exception 'STATUS_HARI_INI_SUDAH_FINAL';
  end if;

  if exists (
    select 1
      from public.jadwal_libur j
     where j.karyawan_id = v_kid
       and j.tanggal = v_day
       and upper(trim(coalesce(j.status,''))) in ('IZIN','SAKIT','LIBUR')
  ) then
    raise exception 'STATUS_HARI_INI_SUDAH_FINAL';
  end if;

  if exists (
    select 1
      from public.pengajuan_pulang_awal p
     where p.karyawan_id = v_kid
       and p.tanggal = v_day
       and p.status in ('MENUNGGU_SPV','DISETUJUI_SPV')
  ) then
    raise exception 'PENGAJUAN_AKTIF_SUDAH_ADA';
  end if;

  insert into public.pengajuan_pulang_awal (
    karyawan_id,cabang_id,absensi_id,tanggal,jenis,alasan,bukti_path,
    jam_masuk_snapshot,jam_pulang_sebelum,
    absensi_status_sebelum,status_absensi_sebelum,
    denda_sebelum,status_denda_sebelum
  )
  values (
    v_kid,v_abs.cabang_id,v_abs.id,v_day,v_kind,v_reason,v_proof,
    v_abs.jam_masuk,v_abs.jam_pulang,
    v_abs.status,v_abs.status_absensi,
    coalesce(v_abs.denda,0),v_abs.status_denda
  )
  returning id into v_id;

  insert into public.pengajuan_pulang_awal_audit(
    pengajuan_id,actor_karyawan_id,actor_role,action,status_after,detail
  ) values (
    v_id,v_kid,'karyawan','SUBMIT','MENUNGGU_SPV',
    jsonb_build_object('jenis',v_kind,'tanggal',v_day,'absensi_id',v_abs.id)
  );

  return jsonb_build_object(
    'ok',true,
    'id',v_id,
    'status','MENUNGGU_SPV',
    'jenis',v_kind,
    'tanggal',v_day,
    'jam_masuk',v_abs.jam_masuk
  );
end;
$$;

create or replace function public.pulang_awal_status_self_v1(
  p_session_token text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_kid bigint;
  v_day date := (now() at time zone 'Asia/Jakarta')::date;
  v_abs public.absensi%rowtype;
  v_req public.pengajuan_pulang_awal%rowtype;
begin
  v_kid := public.karyawan_session_id_from_token(p_session_token);
  if v_kid is null then
    raise exception 'SESSION_INVALID';
  end if;

  select * into v_abs
    from public.absensi
   where karyawan_id=v_kid and tanggal=v_day
   limit 1;

  select * into v_req
    from public.pengajuan_pulang_awal
   where karyawan_id=v_kid and tanggal=v_day
   order by created_at desc
   limit 1;

  return jsonb_build_object(
    'ok',true,
    'tanggal',v_day,
    'absensi',case when v_abs.id is null then null else jsonb_build_object(
      'id',v_abs.id,
      'jam_masuk',v_abs.jam_masuk,
      'jam_pulang',v_abs.jam_pulang,
      'status',v_abs.status,
      'status_absensi',v_abs.status_absensi
    ) end,
    'pengajuan',case when v_req.id is null then null else jsonb_build_object(
      'id',v_req.id,
      'created_at',v_req.created_at,
      'jenis',v_req.jenis,
      'alasan',v_req.alasan,
      'status',v_req.status,
      'spv_catatan',v_req.spv_catatan,
      'spv_reviewed_at',v_req.spv_reviewed_at,
      'jam_pulang_setelah',v_req.jam_pulang_setelah
    ) end
  );
end;
$$;

create or replace function public.review_pulang_awal_spv_v1(
  p_pengajuan_id bigint,
  p_action text,
  p_catatan text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_req public.pengajuan_pulang_awal%rowtype;
  v_abs public.absensi%rowtype;
  v_action text := upper(trim(coalesce(p_action,'')));
  v_note text := trim(coalesce(p_catatan,''));
  v_kind text;
  v_status_text text;
  v_status_char char(1);
  v_now_time time := (now() at time zone 'Asia/Jakarta')::time(0);
  v_day date := (now() at time zone 'Asia/Jakarta')::date;
begin
  if auth.uid() is null or not public.is_erp_spv() then
    raise exception 'SPV_REQUIRED';
  end if;

  if v_action in ('APPROVE','SETUJUI') then v_action := 'ACC'; end if;
  if v_action not in ('ACC','TOLAK') then
    raise exception 'ACTION_INVALID';
  end if;

  if v_action='TOLAK' and char_length(v_note) < 3 then
    raise exception 'CATATAN_TOLAK_WAJIB';
  end if;

  select * into v_req
    from public.pengajuan_pulang_awal
   where id=p_pengajuan_id
   for update;

  if not found then raise exception 'PENGAJUAN_TIDAK_DITEMUKAN'; end if;
  if v_req.status <> 'MENUNGGU_SPV' then raise exception 'PENGAJUAN_SUDAH_DIPUTUS'; end if;

  if v_action='TOLAK' then
    update public.pengajuan_pulang_awal
       set status='DITOLAK_SPV',
           spv_user_id=auth.uid(),
           spv_catatan=nullif(v_note,''),
           spv_reviewed_at=now(),
           updated_at=now()
     where id=v_req.id;

    insert into public.pengajuan_pulang_awal_audit(
      pengajuan_id,actor_user_id,actor_role,action,status_before,status_after,detail
    ) values (
      v_req.id,auth.uid(),'spv','TOLAK','MENUNGGU_SPV','DITOLAK_SPV',
      jsonb_build_object('catatan',v_note)
    );

    return jsonb_build_object('ok',true,'id',v_req.id,'status','DITOLAK_SPV');
  end if;

  if v_req.tanggal <> v_day then
    raise exception 'PENGAJUAN_KADALUARSA: keputusan pulang lebih awal harus pada hari yang sama';
  end if;

  select * into v_abs
    from public.absensi
   where id=v_req.absensi_id
     and karyawan_id=v_req.karyawan_id
   for update;

  if not found then raise exception 'ABSENSI_TIDAK_DITEMUKAN'; end if;
  if v_abs.jam_masuk is null then raise exception 'ABSEN_MASUK_TIDAK_DITEMUKAN'; end if;

  v_kind := upper(trim(v_req.jenis));
  v_status_text := case v_kind when 'SAKIT' then 'Sakit' when 'LIBUR' then 'Libur' else 'Izin' end;
  v_status_char := case v_kind when 'SAKIT' then 'S' when 'LIBUR' then 'L' else 'I' end;

  update public.absensi
     set jam_pulang=coalesce(jam_pulang,v_now_time),
         status=v_status_text,
         status_absensi=v_status_char,
         denda=0,
         status_denda='Dibatalkan - Pulang Lebih Awal',
         updated_at=now()
   where id=v_abs.id
   returning * into v_abs;

  if not exists (
    select 1 from public.jadwal_libur j
     where j.karyawan_id=v_req.karyawan_id
       and j.tanggal=v_req.tanggal
       and upper(trim(coalesce(j.status,''))) in ('IZIN','SAKIT','LIBUR')
  ) then
    insert into public.jadwal_libur(
      karyawan_id,tanggal,status,keterangan,created_by,status_canonical,sumber
    ) values (
      v_req.karyawan_id,
      v_req.tanggal,
      v_kind,
      'Pulang lebih awal: ' || v_req.alasan,
      auth.uid(),
      v_status_char,
      'PULANG_LEBIH_AWAL'
    );
  end if;

  update public.pengajuan_pulang_awal
     set status='DISETUJUI_SPV',
         spv_user_id=auth.uid(),
         spv_catatan=nullif(v_note,''),
         spv_reviewed_at=now(),
         updated_at=now(),
         jam_pulang_setelah=v_abs.jam_pulang,
         absensi_status_setelah=v_abs.status,
         status_absensi_setelah=v_abs.status_absensi
   where id=v_req.id;

  insert into public.pengajuan_pulang_awal_audit(
    pengajuan_id,actor_user_id,actor_role,action,status_before,status_after,detail
  ) values (
    v_req.id,auth.uid(),'spv','ACC','MENUNGGU_SPV','DISETUJUI_SPV',
    jsonb_build_object(
      'jenis',v_kind,
      'absensi_status_before',v_req.absensi_status_sebelum,
      'absensi_status_after',v_abs.status,
      'jam_masuk',v_abs.jam_masuk,
      'jam_pulang',v_abs.jam_pulang,
      'denda_before',v_req.denda_sebelum,
      'denda_after',v_abs.denda
    )
  );

  return jsonb_build_object(
    'ok',true,
    'id',v_req.id,
    'status','DISETUJUI_SPV',
    'jenis',v_kind,
    'absensi_status',v_abs.status,
    'jam_masuk',v_abs.jam_masuk,
    'jam_pulang',v_abs.jam_pulang
  );
end;
$$;

create or replace function public.pulang_awal_list_reviewer_v1(
  p_scope text default 'ALL'
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_role text;
  v_scope text := upper(trim(coalesce(p_scope,'ALL')));
  v_data jsonb;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;

  if public.is_erp_owner() then
    v_role := 'owner';
  elsif public.is_erp_spv() then
    v_role := 'spv';
  else
    raise exception 'ROLE_NOT_ALLOWED';
  end if;

  select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb)
    into v_data
    from (
      select
        p.id,p.created_at,p.updated_at,p.karyawan_id,p.cabang_id,p.absensi_id,
        p.tanggal,p.jenis,p.alasan,p.bukti_path,p.status,
        p.jam_masuk_snapshot,p.jam_pulang_sebelum,p.jam_pulang_setelah,
        p.absensi_status_sebelum,p.absensi_status_setelah,
        p.status_absensi_sebelum,p.status_absensi_setelah,
        p.denda_sebelum,p.status_denda_sebelum,
        p.spv_user_id,p.spv_catatan,p.spv_reviewed_at,
        k.nama_karyawan,k.jabatan,
        c.nama_cabang,
        pr.nama as spv_nama
      from public.pengajuan_pulang_awal p
      left join public.karyawan k on k.id=p.karyawan_id
      left join public.cabang c on c.id=p.cabang_id
      left join public.profiles pr on pr.id=p.spv_user_id
      where
        case
          when v_role='spv' and v_scope='PENDING' then p.status='MENUNGGU_SPV'
          when v_role='spv' and v_scope='DECIDED' then p.status in ('DISETUJUI_SPV','DITOLAK_SPV')
          when v_role='owner' and v_scope='PENDING' then p.status='MENUNGGU_SPV'
          when v_role='owner' and v_scope='DECIDED' then p.status in ('DISETUJUI_SPV','DITOLAK_SPV')
          else true
        end
      order by p.created_at desc
      limit 200
    ) x;

  return jsonb_build_object('ok',true,'role',v_role,'scope',v_scope,'rows',v_data);
end;
$$;

grant execute on function public.submit_pulang_awal_v1(text,text,text,text) to anon, authenticated;
grant execute on function public.pulang_awal_status_self_v1(text) to anon, authenticated;
grant execute on function public.review_pulang_awal_spv_v1(bigint,text,text) to authenticated;
grant execute on function public.pulang_awal_list_reviewer_v1(text) to authenticated;
