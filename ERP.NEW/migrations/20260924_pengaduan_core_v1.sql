create or replace function public.erp_pengaduan_sla_sweep()
returns jsonb
language plpgsql
security definer
set search_path='public','pg_temp'
as $$
declare
  r record;
  v_warn int:=0;
  v_escalate int:=0;
begin
  for r in
    select * from public.erp_pengaduan
    where closed_at is null
      and status not in ('SELESAI','DITUTUP_OTOMATIS')
      and now()>=sla_due_at
      and sla_warning_sent_at is null
  loop
    update public.erp_pengaduan set sla_warning_sent_at=now(),updated_at=now() where id=r.id;
    perform public.erp_pengaduan_notify_staff(r.id,'SVP','PERHATIAN','SLA 4 hari · '||r.ticket_no,
      'Pengaduan sudah mencapai batas target penanganan 4 hari.');
    insert into public.erp_pengaduan_event(pengaduan_id,actor_kind,event_type,status_from,status_to,message)
    values(r.id,'SYSTEM','SLA_WARNING',r.status,r.status,'SLA 4 hari tercapai; reminder dikirim ke SVP.');
    v_warn:=v_warn+1;
  end loop;

  for r in
    select * from public.erp_pengaduan
    where closed_at is null
      and status not in ('SELESAI','DITUTUP_OTOMATIS','ESKALASI_OWNER')
      and now()>=owner_escalate_at
  loop
    update public.erp_pengaduan set
      status='ESKALASI_OWNER',escalated_at=now(),
      escalation_reason=coalesce(escalation_reason,'Melewati 7 hari tanpa penyelesaian SVP.'),
      updated_at=now()
    where id=r.id;

    insert into public.erp_pengaduan_event(pengaduan_id,actor_kind,event_type,status_from,status_to,message)
    values(r.id,'SYSTEM','AUTO_ESCALATION',r.status,'ESKALASI_OWNER','Melewati 7 hari; sistem otomatis meneruskan ke Owner.');

    perform public.erp_pengaduan_notify_staff(r.id,'OWNER','KRITIS','Auto eskalasi 7 hari · '||r.ticket_no,
      'Pengaduan belum selesai dalam 7 hari. Alasan sistem: belum ada penyelesaian SVP.');
    perform public.erp_pengaduan_notify_staff(r.id,'SVP','KRITIS','Pengaduan dieskalasi · '||r.ticket_no,
      'Pengaduan otomatis diteruskan ke Owner karena melewati 7 hari.');

    insert into public.erp_pengaduan_notification(
      pengaduan_id,recipient_kind,recipient_karyawan_id,level,title,body,action_path
    ) values (
      r.id,'KARYAWAN',r.pelapor_id,'PERHATIAN',
      'Pengaduan diteruskan ke Owner · '||r.ticket_no,
      'Pengaduan belum selesai dalam 7 hari dan otomatis dieskalasi ke Owner.',
      'pengaduan.html?ticket='||r.id
    );
    v_escalate:=v_escalate+1;
  end loop;

  return jsonb_build_object('ok',true,'warnings',v_warn,'escalations',v_escalate,'ran_at',now());
end;
$$;
revoke all on function public.erp_pengaduan_sla_sweep() from public;
grant execute on function public.erp_pengaduan_sla_sweep() to service_role;

