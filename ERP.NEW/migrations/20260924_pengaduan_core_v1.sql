create or replace function public.karyawan_pengaduan_confirm_resolution(
  p_token text,p_pengaduan_id bigint,p_selesai boolean,p_catatan text default null
) returns jsonb
language plpgsql
security definer
set search_path='public','pg_temp'
as $$
declare
  v_kid bigint := public.karyawan_session_id_from_token(p_token);
  v public.erp_pengaduan%rowtype;
  v_from text;
begin
  if v_kid is null then return jsonb_build_object('ok',false,'reason','SESSION_INVALID'); end if;
  select * into v from public.erp_pengaduan where id=p_pengaduan_id and pelapor_id=v_kid for update;
  if not found then return jsonb_build_object('ok',false,'reason','NOT_FOUND'); end if;
  if v.status<>'SELESAI_MENUNGGU_KONFIRMASI' then
    return jsonb_build_object('ok',false,'reason','STATUS_NOT_CONFIRMABLE');
  end if;

  v_from:=v.status;
  if p_selesai then
    update public.erp_pengaduan
      set status='SELESAI',employee_confirmed_at=now(),closed_at=now(),updated_at=now()
      where id=v.id;
    insert into public.erp_pengaduan_event(pengaduan_id,actor_kind,actor_karyawan_id,event_type,status_from,status_to,message)
    values(v.id,'KARYAWAN',v_kid,'EMPLOYEE_CONFIRMED',v_from,'SELESAI',coalesce(nullif(trim(p_catatan),''),'Pelapor mengonfirmasi masalah sudah selesai.'));
    perform public.erp_pengaduan_notify_staff(v.id,'SVP','INFO','Pengaduan selesai · '||v.ticket_no,'Pelapor mengonfirmasi masalah sudah selesai.');
    return jsonb_build_object('ok',true,'status','SELESAI');
  else
    update public.erp_pengaduan
      set status='DIBUKA_KEMBALI',resolved_at=null,closed_at=null,updated_at=now()
      where id=v.id;
    insert into public.erp_pengaduan_event(pengaduan_id,actor_kind,actor_karyawan_id,event_type,status_from,status_to,message)
    values(v.id,'KARYAWAN',v_kid,'REOPENED',v_from,'DIBUKA_KEMBALI',coalesce(nullif(trim(p_catatan),''),'Pelapor menyatakan masalah belum selesai.'));
    perform public.erp_pengaduan_notify_staff(v.id,'SVP','PERHATIAN','Pengaduan dibuka kembali · '||v.ticket_no,'Pelapor menyatakan masalah belum selesai.');
    perform public.erp_pengaduan_notify_staff(v.id,'OWNER','PERHATIAN','Pengaduan dibuka kembali · '||v.ticket_no,'Pelapor menolak konfirmasi selesai.');
    return jsonb_build_object('ok',true,'status','DIBUKA_KEMBALI');
  end if;
end;
$$;
revoke all on function public.karyawan_pengaduan_confirm_resolution(text,bigint,boolean,text) from public;
grant execute on function public.karyawan_pengaduan_confirm_resolution(text,bigint,boolean,text) to anon,authenticated;

