-- ERP VAX Pengaduan Core V1
-- Isolated/additive complaint ticketing, SLA, notifications, and audit trail.
-- Does not modify locked attendance/payroll/Minutes/dashboard engines.

create table if not exists public.erp_pengaduan (
  id bigint generated by default as identity primary key,
  ticket_no text unique,
  pelapor_id bigint not null references public.karyawan(id),
  cabang_id bigint references public.cabang(id),
  kategori text not null check (kategori in ('ALAT_KERJA','FASILITAS_BARBER','REKAN_KERJA','LAIN_LAIN')),
  subjek text not null,
  deskripsi text,
  intake_answers jsonb not null default '{}'::jsonb,
  intake_summary text,
  prioritas text not null default 'NORMAL' check (prioritas in ('RENDAH','NORMAL','TINGGI','KRITIS')),
  sensitive boolean not null default false,
  status text not null default 'MENUNGGU_SVP' check (status in (
    'MENUNGGU_SVP','DITERIMA_SVP','DALAM_PENANGANAN','MENUNGGU_INFO',
    'MENUNGGU_TINDAKAN','SELESAI_MENUNGGU_KONFIRMASI','DIBUKA_KEMBALI',
    'ESKALASI_OWNER','SELESAI','DITUTUP_OTOMATIS'
  )),
  svp_user_id uuid,
  owner_user_id uuid,
  estimasi_selesai_at timestamptz,
  sla_due_at timestamptz not null default (now() + interval '4 days'),
  owner_escalate_at timestamptz not null default (now() + interval '7 days'),
  sla_warning_sent_at timestamptz,
  escalated_at timestamptz,
  escalation_reason text,
  resolved_at timestamptz,
  completion_note text,
  employee_confirmed_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_erp_pengaduan_pelapor on public.erp_pengaduan(pelapor_id,created_at desc);
create index if not exists idx_erp_pengaduan_status on public.erp_pengaduan(status,created_at desc);
create index if not exists idx_erp_pengaduan_sla on public.erp_pengaduan(owner_escalate_at) where closed_at is null;

create table if not exists public.erp_pengaduan_event (
  id bigint generated by default as identity primary key,
  pengaduan_id bigint not null references public.erp_pengaduan(id) on delete cascade,
  actor_kind text not null check (actor_kind in ('KARYAWAN','SVP','OWNER','ERP','SYSTEM')),
  actor_karyawan_id bigint references public.karyawan(id),
  actor_user_id uuid,
  event_type text not null,
  status_from text,
  status_to text,
  message text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_erp_pengaduan_event_ticket on public.erp_pengaduan_event(pengaduan_id,created_at);

create table if not exists public.erp_pengaduan_notification (
  id bigint generated by default as identity primary key,
  pengaduan_id bigint references public.erp_pengaduan(id) on delete cascade,
  recipient_kind text not null check (recipient_kind in ('KARYAWAN','SVP','OWNER')),
  recipient_karyawan_id bigint references public.karyawan(id),
  recipient_user_id uuid,
  level text not null default 'INFO' check (level in ('INFO','PERHATIAN','KRITIS')),
  title text not null,
  body text not null,
  action_path text,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  check (
    (recipient_kind='KARYAWAN' and recipient_karyawan_id is not null)
    or (recipient_kind in ('SVP','OWNER') and recipient_user_id is not null)
  )
);
create index if not exists idx_erp_pengaduan_notif_employee on public.erp_pengaduan_notification(recipient_karyawan_id,read_at,created_at desc);
create index if not exists idx_erp_pengaduan_notif_user on public.erp_pengaduan_notification(recipient_user_id,read_at,created_at desc);

alter table public.erp_pengaduan enable row level security;
alter table public.erp_pengaduan_event enable row level security;
alter table public.erp_pengaduan_notification enable row level security;
revoke all on public.erp_pengaduan from anon,authenticated;
revoke all on public.erp_pengaduan_event from anon,authenticated;
revoke all on public.erp_pengaduan_notification from anon,authenticated;

create or replace function public.erp_pengaduan_notify_staff(
  p_pengaduan_id bigint,
  p_kind text,
  p_level text,
  p_title text,
  p_body text
) returns void
language plpgsql
security definer
set search_path='public','pg_temp'
as $$
begin
  if upper(p_kind)='SVP' then
    insert into public.erp_pengaduan_notification(
      pengaduan_id,recipient_kind,recipient_user_id,level,title,body,action_path
    )
    select p_pengaduan_id,'SVP',p.id,upper(p_level),p_title,p_body,
           '../pages/pengaduan.html?ticket='||p_pengaduan_id
    from public.profiles p
    where p.aktif is true and lower(coalesce(p.role,'')) in ('spv','svp');
  elsif upper(p_kind)='OWNER' then
    insert into public.erp_pengaduan_notification(
      pengaduan_id,recipient_kind,recipient_user_id,level,title,body,action_path
    )
    select p_pengaduan_id,'OWNER',p.id,upper(p_level),p_title,p_body,
           '../pages/pengaduan.html?ticket='||p_pengaduan_id
    from public.profiles p
    where p.aktif is true and lower(coalesce(p.role,''))='owner';
  end if;
end;
$$;
revoke all on function public.erp_pengaduan_notify_staff(bigint,text,text,text,text) from public;

