-- VAX WIJAYA Employee SOP Compliance V1
-- Production schema applied 2026-09-29.
-- Direct anon/authenticated table writes are blocked; employee access is through SECURITY DEFINER RPCs.

create table if not exists public.employee_sop_acknowledgement_v1 (
  id bigint generated by default as identity primary key,
  karyawan_id bigint not null references public.karyawan(id) on delete cascade,
  sop_code text not null,
  revision text not null,
  role_snapshot text,
  declaration text not null,
  accepted_at timestamptz not null default now(),
  unique(karyawan_id,sop_code,revision)
);

create table if not exists public.employee_sop_daily_v1 (
  id bigint generated by default as identity primary key,
  karyawan_id bigint not null references public.karyawan(id) on delete cascade,
  cabang_id bigint references public.cabang(id),
  attendance_id bigint references public.absensi(id),
  work_date date not null,
  phase text not null default 'OPENING' check (phase in ('OPENING','CLOSING')),
  role_snapshot text,
  sop_code text not null,
  revision text not null,
  answers jsonb not null default '[]'::jsonb,
  declaration text not null,
  completed_at timestamptz not null default now(),
  unique(karyawan_id,work_date,phase,sop_code,revision)
);

create table if not exists public.employee_sop_audit_finding_v1 (
  id bigint generated by default as identity primary key,
  daily_checklist_id bigint references public.employee_sop_daily_v1(id) on delete set null,
  karyawan_id bigint not null references public.karyawan(id) on delete cascade,
  cabang_id bigint references public.cabang(id),
  finding_date date not null default (timezone('Asia/Jakarta',now()))::date,
  finding_type text not null default 'MISMATCH',
  notes text not null,
  evidence_path text,
  action_level text check (action_level is null or action_level in ('PEMBINAAN','SP1','SP2','SP3','PEMBERHENTIAN')),
  owner_user_id uuid,
  created_at timestamptz not null default now()
);

create index if not exists idx_employee_sop_daily_employee_date
  on public.employee_sop_daily_v1(karyawan_id,work_date desc);
create index if not exists idx_employee_sop_daily_branch_date
  on public.employee_sop_daily_v1(cabang_id,work_date desc);
create index if not exists idx_employee_sop_audit_employee_date
  on public.employee_sop_audit_finding_v1(karyawan_id,finding_date desc);

alter table public.employee_sop_acknowledgement_v1 enable row level security;
alter table public.employee_sop_daily_v1 enable row level security;
alter table public.employee_sop_audit_finding_v1 enable row level security;

revoke all on public.employee_sop_acknowledgement_v1 from anon, authenticated;
revoke all on public.employee_sop_daily_v1 from anon, authenticated;
revoke all on public.employee_sop_audit_finding_v1 from anon, authenticated;

create or replace function public.employee_sop_status_self(
  p_token text,
  p_sop_code text,
  p_revision text
) returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions'
as $$
declare
  v_kid bigint;
  v_accepted boolean;
begin
  v_kid := public.karyawan_session_id_from_token(p_token);
  if v_kid is null then
    return jsonb_build_object('ok',false,'reason','SESSION_INVALID','accepted',false);
  end if;

  select exists(
    select 1 from public.employee_sop_acknowledgement_v1 a
    where a.karyawan_id=v_kid and a.sop_code=p_sop_code and a.revision=p_revision
  ) into v_accepted;

  return jsonb_build_object('ok',true,'accepted',v_accepted);
end;
$$;

create or replace function public.employee_sop_accept_self(
  p_token text,
  p_sop_code text,
  p_revision text
) returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions'
as $$
declare
  v_kid bigint;
  v_role text;
begin
  v_kid := public.karyawan_session_id_from_token(p_token);
  if v_kid is null then
    return jsonb_build_object('ok',false,'reason','SESSION_INVALID');
  end if;

  select k.jabatan into v_role from public.karyawan k where k.id=v_kid;

  insert into public.employee_sop_acknowledgement_v1
    (karyawan_id,sop_code,revision,role_snapshot,declaration,accepted_at)
  values
    (v_kid,p_sop_code,p_revision,v_role,
     'Saya telah membaca, memahami, dan menyetujui untuk mematuhi SOP VAX WIJAYA.',
     now())
  on conflict (karyawan_id,sop_code,revision)
  do update set
    role_snapshot=excluded.role_snapshot,
    declaration=excluded.declaration,
    accepted_at=excluded.accepted_at;

  return jsonb_build_object('ok',true);
end;
$$;

create or replace function public.employee_sop_daily_status_self(
  p_token text,
  p_work_date date,
  p_phase text,
  p_sop_code text,
  p_revision text
) returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions'
as $$
declare
  v_kid bigint;
  v_completed boolean;
begin
  v_kid := public.karyawan_session_id_from_token(p_token);
  if v_kid is null then
    return jsonb_build_object('ok',false,'reason','SESSION_INVALID','completed',false);
  end if;

  select exists(
    select 1 from public.employee_sop_daily_v1 d
    where d.karyawan_id=v_kid
      and d.work_date=p_work_date
      and d.phase=upper(coalesce(p_phase,'OPENING'))
      and d.sop_code=p_sop_code
      and d.revision=p_revision
  ) into v_completed;

  return jsonb_build_object('ok',true,'completed',v_completed);
end;
$$;

create or replace function public.employee_sop_daily_submit_self(
  p_token text,
  p_work_date date,
  p_phase text,
  p_sop_code text,
  p_revision text,
  p_answers jsonb,
  p_declaration text
) returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions'
as $$
declare
  v_kid bigint;
  v_role text;
  v_attendance_id bigint;
  v_cabang_id bigint;
  v_phase text := upper(coalesce(p_phase,'OPENING'));
begin
  v_kid := public.karyawan_session_id_from_token(p_token);
  if v_kid is null then
    return jsonb_build_object('ok',false,'reason','SESSION_INVALID');
  end if;

  if p_work_date <> (timezone('Asia/Jakarta',now()))::date then
    return jsonb_build_object('ok',false,'reason','WORK_DATE_INVALID');
  end if;

  if v_phase <> 'OPENING' then
    return jsonb_build_object('ok',false,'reason','PHASE_INVALID');
  end if;

  if jsonb_typeof(p_answers) <> 'array' or jsonb_array_length(p_answers) < 1 then
    return jsonb_build_object('ok',false,'reason','ANSWERS_INVALID');
  end if;

  if exists (
    select 1 from jsonb_array_elements(p_answers) e
    where coalesce((e->>'checked')::boolean,false) is not true
  ) then
    return jsonb_build_object('ok',false,'reason','CHECKLIST_INCOMPLETE');
  end if;

  select a.id,a.cabang_id
    into v_attendance_id,v_cabang_id
  from public.absensi a
  where a.karyawan_id=v_kid
    and a.tanggal=p_work_date
    and a.jam_masuk is not null
  order by a.id desc
  limit 1;

  if v_attendance_id is null then
    return jsonb_build_object('ok',false,'reason','ABSEN_MASUK_REQUIRED');
  end if;

  select k.jabatan into v_role from public.karyawan k where k.id=v_kid;

  insert into public.employee_sop_daily_v1
    (karyawan_id,cabang_id,attendance_id,work_date,phase,role_snapshot,sop_code,revision,answers,declaration,completed_at)
  values
    (v_kid,v_cabang_id,v_attendance_id,p_work_date,v_phase,v_role,p_sop_code,p_revision,p_answers,p_declaration,now())
  on conflict (karyawan_id,work_date,phase,sop_code,revision)
  do update set
    cabang_id=excluded.cabang_id,
    attendance_id=excluded.attendance_id,
    role_snapshot=excluded.role_snapshot,
    answers=excluded.answers,
    declaration=excluded.declaration,
    completed_at=excluded.completed_at;

  return jsonb_build_object('ok',true,'attendance_id',v_attendance_id);
end;
$$;

