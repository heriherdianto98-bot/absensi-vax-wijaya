create table if not exists public.laporan_bulanan_provider_mapping (
  id bigint generated by default as identity primary key,
  source_provider_row_id bigint not null unique,
  period_month date not null,
  source_cabang_id bigint,
  source_provider_name text,
  source_provider_share numeric not null default 0,
  employee_id bigint not null,
  employee_cabang_id bigint not null,
  employee_name_snapshot text,
  branch_name_snapshot text,
  created_by uuid,
  updated_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_laporan_bulanan_provider_mapping_period
  on public.laporan_bulanan_provider_mapping(period_month);
create index if not exists idx_laporan_bulanan_provider_mapping_employee
  on public.laporan_bulanan_provider_mapping(employee_id);

alter table public.laporan_bulanan_provider_mapping enable row level security;

drop policy if exists laporan_bulanan_provider_mapping_read on public.laporan_bulanan_provider_mapping;
create policy laporan_bulanan_provider_mapping_read
on public.laporan_bulanan_provider_mapping
for select
to authenticated
using (true);

drop policy if exists laporan_bulanan_provider_mapping_write on public.laporan_bulanan_provider_mapping;
create policy laporan_bulanan_provider_mapping_write
on public.laporan_bulanan_provider_mapping
for all
to authenticated
using (true)
with check (true);
