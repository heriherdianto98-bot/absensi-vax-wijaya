create table if not exists public.master_investor (
  id bigint generated by default as identity primary key,
  branch_code text not null,
  branch_name text not null,
  investor_name text not null,
  profit_share_percent numeric(5,2) not null check (profit_share_percent >= 0 and profit_share_percent <= 100),
  rent_entitlement boolean not null default true,
  profit_basis text not null default 'LABA_BERSIH',
  deductions_before_share text not null default 'SEWA + GAJI + OPERASIONAL + BIAYA_LAIN_DISETUJUI',
  payment_day_start smallint not null default 10 check (payment_day_start between 1 and 31),
  payment_day_end smallint not null default 15 check (payment_day_end between 1 and 31),
  payment_timing text not null default 'AWAL_BULAN',
  status text not null default 'AKTIF' check (status in ('AKTIF','NONAKTIF')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(branch_code)
);

