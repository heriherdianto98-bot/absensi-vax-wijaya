-- =========================================================
-- ERP VAX — MASTER BIAYA SEWA TEMPAT V1
-- Source of truth biaya sewa bulanan per cabang.
-- Tidak untuk investor/share.
-- =========================================================

create table if not exists public.master_biaya_sewa_tempat (
  id bigint generated by default as identity primary key,
  branch_code text not null unique,
  branch_name text not null,
  monthly_rent numeric(14,2) not null check (monthly_rent >= 0),
  period_type text not null default 'BULANAN' check (period_type in ('BULANAN')),
  due_rule text not null default 'AKHIR_BULAN' check (due_rule in ('AKHIR_BULAN')),
  loss_rule text not null default 'JADI_HUTANG_BULAN_BERIKUTNYA',
  effective_from date null,
  effective_to date null,
  status text not null default 'AKTIF' check (status in ('AKTIF','SELESAI')),
  notes text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.master_biaya_sewa_tempat is
'Master biaya sewa tempat ERP VAX. Source of truth biaya sewa bulanan per cabang. Jangan gunakan untuk investor/share.';

